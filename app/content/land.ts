const CELLS: Uint8Array = (() => {
  const out = new Uint8Array(MASK_COLS * MASK_ROWS);
  let index = 0;
  let value = 0;

  for (const part of RUNS.split(",")) {
    const length = Number(part);
    if (value === 1) out.fill(1, index, index + length);
    index += length;
    value ^= 1;
  }

  return out;
})();

/** True when the given coordinate falls on land. */
export function isLand(latDeg: number, lonDeg: number): boolean {
  const col = Math.floor(((lonDeg + 180) % 360) / MASK_STEP);
  const row = Math.floor((90 - latDeg) / MASK_STEP);

  if (row < 0 || row >= MASK_ROWS) return false;

  return CELLS[row * MASK_COLS + ((col % MASK_COLS) + MASK_COLS) % MASK_COLS] === 1;
}
